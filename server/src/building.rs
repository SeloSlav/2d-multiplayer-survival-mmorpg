/// Check if a position is within a monument zone (rune stones, ALK stations, hot springs, quarries)
/// Returns an error message if placement is blocked, or Ok(()) if allowed
/// This function is used by all placement reducers (seeds, placeables, foundations)
pub fn check_monument_zone_placement(ctx: &ReducerContext, world_x: f32, world_y: f32) -> Result<(), String> {
    // Check ALK station monument bounds (same logic as foundation placement)
    const ALK_STATION_BUILDING_RESTRICTION_MULTIPLIER_CENTRAL: f32 = 8.75;
    const ALK_STATION_BUILDING_RESTRICTION_MULTIPLIER_SUBSTATION: f32 = 3.0;
    
    let alk_stations = ctx.db.alk_station();
    for station in alk_stations.iter() {
        if !station.is_active {
            continue;
        }
        let dx = world_x - station.world_pos_x;
        let dy = world_y - station.world_pos_y;
        let distance_sq = dx * dx + dy * dy;
        
        // Calculate building restriction radius (matches safe zone radius)
        let multiplier = if station.station_id == 0 {
            ALK_STATION_BUILDING_RESTRICTION_MULTIPLIER_CENTRAL
        } else {
            ALK_STATION_BUILDING_RESTRICTION_MULTIPLIER_SUBSTATION
        };
        let restriction_radius = station.interaction_radius * multiplier;
        let restriction_radius_sq = restriction_radius * restriction_radius;
        
        if distance_sq <= restriction_radius_sq {
            return Err("Cannot place items within ALK station compound. These areas are protected.".to_string());
        }
    }
    
    // Check rune stones (same 800px radius as foundations)
    const MONUMENT_PLACEMENT_RESTRICTION_RADIUS: f32 = 800.0; // 800px = ~16 tiles
    const MONUMENT_PLACEMENT_RESTRICTION_RADIUS_SQ: f32 = MONUMENT_PLACEMENT_RESTRICTION_RADIUS * MONUMENT_PLACEMENT_RESTRICTION_RADIUS;
    
    let rune_stones = ctx.db.rune_stone();
    for rune_stone in rune_stones.iter() {
        let dx = world_x - rune_stone.pos_x;
        let dy = world_y - rune_stone.pos_y;
        let distance_sq = dx * dx + dy * dy;
        
        if distance_sq <= MONUMENT_PLACEMENT_RESTRICTION_RADIUS_SQ {
            return Err("Cannot place items within a rune stone's light area. These monuments must remain unobstructed.".to_string());
        }
    }
    
    // Check hot springs and quarries (different radii: hot springs 800px, quarries 400px)
    // OPTIMIZATION: Use indexed lookups per tile (O(log n) each) but only check tiles within radius
    // Most tiles don't exist (sparse world), so empty lookups are very fast
    // Early exit when monument found - typical case: 0-1 monuments in search area
    const QUARRY_PLACEMENT_RESTRICTION_RADIUS: f32 = 400.0; // 400px for quarries
    const QUARRY_PLACEMENT_RESTRICTION_RADIUS_SQ: f32 = QUARRY_PLACEMENT_RESTRICTION_RADIUS * QUARRY_PLACEMENT_RESTRICTION_RADIUS;
    
    let tile_size = crate::TILE_SIZE_PX as f32;
    // Use the larger radius (hot springs 800px) for the search area
    let check_radius_tiles = (MONUMENT_PLACEMENT_RESTRICTION_RADIUS / tile_size).ceil() as i32 + 1;
    let center_tile_x = (world_x / tile_size).floor() as i32;
    let center_tile_y = (world_y / tile_size).floor() as i32;
    
    let world_tiles = ctx.db.world_tile();
    
    // Pre-calculate tile center positions to avoid repeated calculations
    let world_tile_size_f32 = tile_size;
    let half_tile = tile_size / 2.0;
    
    // Check tiles in a square around the position (optimized: early exit on first monument found)
    for dy in -check_radius_tiles..=check_radius_tiles {
        for dx in -check_radius_tiles..=check_radius_tiles {
            let check_tile_x = center_tile_x + dx;
            let check_tile_y = center_tile_y + dy;
            
            // OPTIMIZATION: Quick distance check before expensive lookup
            // If tile is definitely outside radius, skip lookup entirely
            let tile_center_x = (check_tile_x as f32 * world_tile_size_f32) + half_tile;
            let tile_center_y = (check_tile_y as f32 * world_tile_size_f32) + half_tile;
            let quick_dx = world_x - tile_center_x;
            let quick_dy = world_y - tile_center_y;
            let quick_dist_sq = quick_dx * quick_dx + quick_dy * quick_dy;
            
            // Skip if definitely outside radius (with small margin for tile size)
            if quick_dist_sq > (MONUMENT_PLACEMENT_RESTRICTION_RADIUS_SQ + (tile_size * tile_size)) {
                continue;
            }
            
            // Use indexed lookup for this specific tile (O(log n) - very fast)
            for tile in world_tiles.idx_world_position().filter((check_tile_x, check_tile_y)) {
                // Early exit: Skip non-monument tiles immediately
                if tile.tile_type != crate::TileType::HotSpringWater && tile.tile_type != crate::TileType::Quarry {
                    continue;
                }
                
                // Calculate exact distance from world position to tile center
                let tile_center_x_exact = (tile.world_x as f32 * world_tile_size_f32) + half_tile;
                let tile_center_y_exact = (tile.world_y as f32 * world_tile_size_f32) + half_tile;
                let tdx = world_x - tile_center_x_exact;
                let tdy = world_y - tile_center_y_exact;
                let distance_sq = tdx * tdx + tdy * tdy;
                
                // Use different restriction radii for different tile types
                let (restriction_radius_sq, monument_type) = if tile.tile_type == crate::TileType::HotSpringWater {
                    (MONUMENT_PLACEMENT_RESTRICTION_RADIUS_SQ, "hot springs")
                } else {
                    (QUARRY_PLACEMENT_RESTRICTION_RADIUS_SQ, "quarries")
                };
                
                // Early exit: Found a monument within restriction radius
                if distance_sq <= restriction_radius_sq {
                    return Err(format!("Cannot place items near {}. These monuments must remain unobstructed.", monument_type));
                }
            }
        }
    }
    
    // Check all monument types in the monument_part table (single iteration for performance)
    // Each monument type has different restriction radii:
    // - Shipwreck: 1500px (2.5x clearance radius)
    // - Fishing Village: 1000px (25% larger than original 800)
    // - Whale Bone Graveyard: 800px
    // - Hunting Village: 800px
    const FISHING_VILLAGE_RESTRICTION_RADIUS: f32 = 1000.0; // 25% larger than original 800
    const FISHING_VILLAGE_RESTRICTION_RADIUS_SQ: f32 = FISHING_VILLAGE_RESTRICTION_RADIUS * FISHING_VILLAGE_RESTRICTION_RADIUS;
    const SHIPWRECK_RESTRICTION_RADIUS: f32 = 1875.0; // 25% larger than original 1500
    const SHIPWRECK_RESTRICTION_RADIUS_SQ: f32 = SHIPWRECK_RESTRICTION_RADIUS * SHIPWRECK_RESTRICTION_RADIUS;
    const WHALE_BONE_GRAVEYARD_RESTRICTION_RADIUS: f32 = 800.0; // Same as fishing village
    const WHALE_BONE_GRAVEYARD_RESTRICTION_RADIUS_SQ: f32 = WHALE_BONE_GRAVEYARD_RESTRICTION_RADIUS * WHALE_BONE_GRAVEYARD_RESTRICTION_RADIUS;
    const HUNTING_VILLAGE_RESTRICTION_RADIUS: f32 = 800.0; // Same as fishing village
    const HUNTING_VILLAGE_RESTRICTION_RADIUS_SQ: f32 = HUNTING_VILLAGE_RESTRICTION_RADIUS * HUNTING_VILLAGE_RESTRICTION_RADIUS;
    const CRASHED_RESEARCH_DRONE_RESTRICTION_RADIUS: f32 = 800.0; // Tundra monument (800px minimum)
    const CRASHED_RESEARCH_DRONE_RESTRICTION_RADIUS_SQ: f32 = CRASHED_RESEARCH_DRONE_RESTRICTION_RADIUS * CRASHED_RESEARCH_DRONE_RESTRICTION_RADIUS;
    const WEATHER_STATION_RESTRICTION_RADIUS: f32 = 2000.0; // Four radars, central compound, 2000px exclusion
    const WEATHER_STATION_RESTRICTION_RADIUS_SQ: f32 = WEATHER_STATION_RESTRICTION_RADIUS * WEATHER_STATION_RESTRICTION_RADIUS;
    const WOLF_DEN_RESTRICTION_RADIUS: f32 = 800.0; // Wolf den mound monument (800px minimum)
    const WOLF_DEN_RESTRICTION_RADIUS_SQ: f32 = WOLF_DEN_RESTRICTION_RADIUS * WOLF_DEN_RESTRICTION_RADIUS;
    const ALPINE_VILLAGE_RESTRICTION_RADIUS: f32 = 800.0; // Alpine village lodge (800px minimum, like other monuments)
    const ALPINE_VILLAGE_RESTRICTION_RADIUS_SQ: f32 = ALPINE_VILLAGE_RESTRICTION_RADIUS * ALPINE_VILLAGE_RESTRICTION_RADIUS;
    
    for part in ctx.db.monument_part().iter() {
        // Only check against center pieces for simplicity
        // This creates circular exclusion zones around monument centers
        if !part.is_center {
            continue;
        }
        
        let dx = world_x - part.world_x;
        let dy = world_y - part.world_y;
        let distance_sq = dx * dx + dy * dy;
        
        match part.monument_type {
            MonumentType::Shipwreck => {
                if distance_sq <= SHIPWRECK_RESTRICTION_RADIUS_SQ {
                    return Err("Cannot place items within the Shipwreck. This monument must remain unobstructed.".to_string());
                }
            }
            MonumentType::FishingVillage => {
                if distance_sq <= FISHING_VILLAGE_RESTRICTION_RADIUS_SQ {
                    return Err("Cannot place items within the Fishing Village. This monument must remain unobstructed.".to_string());
                }
            }
            MonumentType::WhaleBoneGraveyard => {
                if distance_sq <= WHALE_BONE_GRAVEYARD_RESTRICTION_RADIUS_SQ {
                    return Err("Cannot place items within the Whale Bone Graveyard. This monument must remain unobstructed.".to_string());
                }
            }
            MonumentType::HuntingVillage => {
                if distance_sq <= HUNTING_VILLAGE_RESTRICTION_RADIUS_SQ {
                    return Err("Cannot place items within the Hunting Village. This monument must remain unobstructed.".to_string());
                }
            }
            MonumentType::CrashedResearchDrone => {
                if distance_sq <= CRASHED_RESEARCH_DRONE_RESTRICTION_RADIUS_SQ {
                    return Err("Cannot place items within the Crashed Research Drone site. This monument must remain unobstructed.".to_string());
                }
            }
            MonumentType::HotSpring => {
                // Hot spring shacks are visual doodads only, no placement restriction
                // (Hot spring water tiles already have their own restriction via TileType check above)
            }
            MonumentType::WeatherStation => {
                if distance_sq <= WEATHER_STATION_RESTRICTION_RADIUS_SQ {
                    return Err("Cannot place items within the Weather Station. This monument must remain unobstructed.".to_string());
                }
            }
            MonumentType::WolfDen => {
                if distance_sq <= WOLF_DEN_RESTRICTION_RADIUS_SQ {
                    return Err("Cannot place items within the Wolf Den. This monument must remain unobstructed.".to_string());
                }
            }
            MonumentType::AlpineVillage => {
                if distance_sq <= ALPINE_VILLAGE_RESTRICTION_RADIUS_SQ {
                    return Err("Cannot place items within the Alpine Village. This monument must remain unobstructed.".to_string());
                }
            }
        }
    }
    
    // Check reed marsh zones (environmental monuments in rivers - tern hunting/reed collection)
    // Building restriction radius matches the marsh radius stored in database
    for marsh in ctx.db.reed_marsh().iter() {
        let dx = world_x - marsh.world_x;
        let dy = world_y - marsh.world_y;
        let distance_sq = dx * dx + dy * dy;
        let marsh_radius_sq = marsh.radius_px * marsh.radius_px;
        
        if distance_sq <= marsh_radius_sq {
            return Err("Cannot place items within the Reed Marsh. This natural area must remain unobstructed.".to_string());
        }
    }
    
    // Check tide pool zones (coastal beach inlets - crabs, terns, reeds)
    for pool in ctx.db.tide_pool().iter() {
        let dx = world_x - pool.world_x;
        let dy = world_y - pool.world_y;
        let distance_sq = dx * dx + dy * dy;
        let pool_radius_sq = pool.radius_px * pool.radius_px;
        
        if distance_sq <= pool_radius_sq {
            return Err("Cannot place items within the Tide Pool. This coastal inlet must remain unobstructed.".to_string());
        }
    }
    
    Ok(())
}

